"""Independent 5x7 text reference for the footer SPI regression."""
from pathlib import Path

ROWS = {
    'F': '#####/#..../#..../####./#..../#..../#....',
    'P': '####./#...#/#...#/####./#..../#..../#....',
    'G': '.###./#...#/#..../#.###/#...#/#...#/.###.',
    'A': '.###./#...#/#...#/#####/#...#/#...#/#...#',
    'C': '.###./#...#/#..../#..../#..../#...#/.###.',
    '°': '.##../#..#./#..#./.##../...../...../.....',
    '-': '...../...../...../#####/...../...../.....',
    ' ': '...../...../...../...../...../...../.....',
    '1': '..#../.##../..#../..#../..#../..#../.###.',
    '2': '.###./#...#/....#/...#./..#../.#.../#####',
    '4': '...#./..##./.#.#./#..#./#####/...#./...#.',
    '5': '#####/#..../#..../####./....#/....#/####.',
    '7': '#####/....#/...#./..#../.#.../.#.../.#...',
    '0': '.###./#...#/#..##/#.#.#/##..#/#...#/.###.',
    '3': '####./....#/....#/.###./....#/....#/####.',
    '6': '.###./#..../#..../####./#...#/#...#/.###.',
    '8': '.###./#...#/#...#/.###./#...#/#...#/.###.',
    '9': '.###./#...#/#...#/.####/....#/....#/.###.',
}

with Path('footer.mem').open('w') as output:
    for text in ('FPGA  47°C', 'FPGA  -5°C', 'FPGA 125°C', 'FPGA ---°C', 'FPGA   7°C',
                 'FPGA   0°C', 'FPGA  38°C', 'FPGA  69°C', 'FPGA -40°C', 'FPGA 100°C'):
        assert len(text) == 10
        for y in range(32):
            for x in range(240):
                ink = False
                if 30 <= x < 210 and 5 <= y < 26:
                    cell, offset = divmod(x - 30, 18)
                    col, row = offset // 3, (y - 5) // 3
                    ink = col < 5 and ROWS[text[cell]].split('/')[row][col] == '#'
                output.write('0000\n' if ink else 'ffff\n')
